import { existsSync, readFileSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { applyEdits, modify, type ParseError, parse } from "jsonc-parser";
import { writeTextFile } from "../fs/write";

/** Directory / package name used for the OpenCode plugin entry. */
export const NOVEL_PLUGIN_NAME = "opencode-novel";

/** First line written into the generated OpenCode 2.x plugin shim. */
export const GENERATED_SHIM_HEADER = "// Generated by opencode-novel. Do not edit.";

/** Paths involved in installing the plugin into an OpenCode config directory. */
export type PluginInstallPaths = {
  /** `<opencode>/plugins` */
  readonly pluginsDir: string;
  /** `<opencode>/plugins/opencode-novel` (OpenCode 2.x loads directories). */
  readonly pluginDir: string;
  /** `<opencode>/plugins/opencode-novel/index.js` */
  readonly entryPath: string;
  /** `<opencode>/plugins/opencode-novel.js` (OpenCode 1.x shim). */
  readonly legacyEntryPath: string;
};

/** Result of a plugin-related OpenCode config update. */
export type PluginConfigUpdate = {
  /** Whether the config file needs to be (or was) written. */
  readonly changed: boolean;
  /** Plugin specs removed from the config. */
  readonly removed: readonly string[];
  /** Set when the config could not be parsed and was left untouched. */
  readonly skippedReason?: string;
};

/**
 * Resolve every path needed to install or uninstall the plugin shim.
 *
 * OpenCode 2.x requires local plugins to be directories; the legacy OpenCode
 * 1.x installer wrote a sibling `opencode-novel.js` file instead.
 */
export function resolvePluginInstallPaths(installRoot: string): PluginInstallPaths {
  const pluginsDir = path.join(installRoot, "plugins");
  const pluginDir = path.join(pluginsDir, NOVEL_PLUGIN_NAME);
  const entryPath = path.join(pluginDir, "index.js");
  const legacyEntryPath = path.join(pluginsDir, `${NOVEL_PLUGIN_NAME}.js`);

  return {
    pluginsDir,
    pluginDir,
    entryPath,
    legacyEntryPath,
  };
}

/** Render the ESM shim that OpenCode 2.x loads from `plugins/opencode-novel/index.js`. */
export function renderPluginShim(distEntry: string): string {
  const distUrl = pathToFileURL(distEntry).toString();
  return `${GENERATED_SHIM_HEADER}\nexport { default } from ${JSON.stringify(distUrl)};\n`;
}

/** Whether a file starts with {@link GENERATED_SHIM_HEADER}. */
export function isGeneratedPluginShim(content: string): boolean {
  return content.trimStart().startsWith(GENERATED_SHIM_HEADER);
}

/**
 * Delete the generated OpenCode 2.x shim.
 *
 * Refuses to delete hand-edited files unless `force` is set; `dryRun` reports
 * the planned deletion without touching the filesystem.
 */
export function removeGeneratedPluginShim(
  filePath: string,
  options: { dryRun: boolean; force: boolean },
): { removed: boolean; skipped: boolean; reason?: string } {
  if (!existsSync(filePath)) return { removed: false, skipped: true, reason: "missing" };

  if (!options.force) {
    let content = "";
    try {
      content = readFileSync(filePath, "utf8");
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      return { removed: false, skipped: true, reason: `read failed: ${message}` };
    }
    if (!isGeneratedPluginShim(content)) {
      return { removed: false, skipped: true, reason: "modified (use --force)" };
    }
  }

  if (options.dryRun) return { removed: true, skipped: false };

  try {
    rmSync(filePath, { recursive: true, force: true });
    return { removed: true, skipped: false };
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return { removed: false, skipped: true, reason: message };
  }
}

/**
 * Remove stale plugin entries from `opencode.json`/`opencode.jsonc`.
 *
 * OpenCode 2.x auto-discovers plugins under `<opencode>/plugins/`, so the shim
 * does not need a config entry. Older installers wrote either a
 * `plugins/opencode-novel.js` file (OpenCode 1.x) or an explicit `plugins`
 * entry; both are cleaned up because OpenCode 2.x rejects file targets and the
 * explicit entry would load the same plugin twice. Other entries (including
 * `{ package, options }` objects) are preserved verbatim.
 */
export function updatePluginConfig(options: {
  configPath: string;
  paths: PluginInstallPaths;
  dryRun?: boolean;
}): PluginConfigUpdate {
  const raw = readConfig(options.configPath);
  const parsed = parseJsoncObject(raw);
  if (!parsed.data) {
    return {
      changed: false,
      removed: [],
      skippedReason: parsed.errors[0] ?? "config must be a JSON object",
    };
  }

  const baseDir = path.dirname(options.configPath);
  const currentPlugins = toEntryArray(parsed.data.plugins);
  const currentLegacy = toEntryArray(parsed.data.plugin);

  const removed: string[] = [];
  const matchesInstalled = (entry: unknown): boolean =>
    matchesPath(entry, options.paths.entryPath, baseDir) ||
    matchesPath(entry, options.paths.pluginDir, baseDir);
  const nextPlugins = currentPlugins.filter((entry) => {
    if (!matchesInstalled(entry) && !matchesPath(entry, options.paths.legacyEntryPath, baseDir)) {
      return true;
    }
    removed.push(describeEntry(entry));
    return false;
  });

  const nextLegacy = currentLegacy.filter((entry) => {
    if (!matchesInstalled(entry) && !matchesPath(entry, options.paths.legacyEntryPath, baseDir)) {
      return true;
    }
    removed.push(describeEntry(entry));
    return false;
  });

  let text = raw;
  if (JSON.stringify(nextLegacy) !== JSON.stringify(currentLegacy)) {
    text = applyPluginField(text, "plugin", nextLegacy);
  }
  if (JSON.stringify(nextPlugins) !== JSON.stringify(currentPlugins)) {
    text = applyPluginField(text, "plugins", nextPlugins);
  }

  const changed = text !== raw;
  if (changed && !options.dryRun) {
    writeTextFile(options.configPath, text, { mode: "always" });
  }

  return { changed, removed };
}

/** Read a config file, falling back to a minimal config document. */
function readConfig(configPath: string): string {
  try {
    const raw = readFileSync(configPath, "utf8");
    if (raw.trim().length > 0) return raw;
  } catch {
    // Missing/unreadable files are created from the default document below.
  }
  return `{\n  "$schema": "https://opencode.ai/config.json"\n}\n`;
}

/** Parse JSONC into an object, collecting parse errors. */
function parseJsoncObject(raw: string): {
  data: Record<string, unknown> | null;
  errors: string[];
} {
  const parseErrors: ParseError[] = [];
  const parsed = parse(raw, parseErrors) as unknown;
  const errors = parseErrors.map(
    (error) => `JSONC parse error: code=${error.error} offset=${error.offset}`,
  );

  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    errors.push("Config root must be a JSON object.");
    return { data: null, errors };
  }

  return { data: parsed as Record<string, unknown>, errors };
}

/** Normalize a `plugins`/`plugin` value into an editable list of entries. */
function toEntryArray(value: unknown): unknown[] {
  if (typeof value === "string" || isRecord(value)) return [value];
  return Array.isArray(value) ? [...value] : [];
}

/** Whether a value is a non-array object. */
function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

/** Resolve a local plugin specifier (`file://`, `./x`, `../x` or absolute) to a path. */
function toLocalPath(specifier: string, baseDir: string): string | undefined {
  if (specifier.startsWith("file://")) {
    try {
      return path.normalize(fileURLToPath(specifier));
    } catch {
      return undefined;
    }
  }
  if (path.isAbsolute(specifier)) return path.normalize(specifier);
  if (specifier.startsWith("./") || specifier.startsWith("../")) {
    return path.resolve(baseDir, specifier);
  }
  return undefined;
}

/** Match a `plugins` entry (string or `{ package }`) against a local path. */
function matchesPath(entry: unknown, target: string, baseDir: string): boolean {
  const specifier =
    typeof entry === "string"
      ? entry
      : isRecord(entry) && typeof entry.package === "string"
        ? entry.package
        : undefined;
  if (!specifier) return false;
  const resolved = toLocalPath(specifier, baseDir);
  return resolved !== undefined && resolved === path.normalize(target);
}

/** Human-readable description of a config entry for CLI output. */
function describeEntry(entry: unknown): string {
  if (typeof entry === "string") return entry;
  if (isRecord(entry) && typeof entry.package === "string") return entry.package;
  return JSON.stringify(entry);
}

/** Write a normalized entry array back, deleting the field when it becomes empty. */
function applyPluginField(text: string, field: "plugin" | "plugins", entries: unknown[]): string {
  const value = entries.length > 0 ? entries : undefined;
  const edits = modify(text, [field], value, {
    formattingOptions: { insertSpaces: true, tabSize: 2, eol: "\n" },
  });
  return applyEdits(text, edits);
}
